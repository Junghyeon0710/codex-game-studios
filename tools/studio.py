#!/usr/bin/env python3
"""Generate and validate the Codex port without calling a model or an engine."""
from pathlib import Path
import argparse
import json
import re
import shutil
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = '''You are a Codex Game Studios specialist. First read AGENTS.md and
.codex/docs/codex-runtime.md. The role below is your domain brief, not a grant of
permissions. Follow current user authorization and host controls. Use the tools
actually available in this Codex session. Questions from a subagent go to its
parent; do not wait invisibly for a user. Delegate only when the workflow calls
for independent specialist work and the host permits it. If custom agent types
are unavailable, the parent may pass this brief to a supported worker, or perform
it sequentially and disclose that fallback. Report changed paths, verification
commands and actual outcomes; never infer execution from an instruction file.

'''

def frontmatter(path):
    text = path.read_text(encoding='utf-8')
    if not text.startswith('---\n'):
        raise ValueError(f'{path}: missing frontmatter')
    front, body = text[4:].split('\n---', 1)
    # Generated native files need only name/description. PyYAML is used for
    # source YAML because folded and escaped descriptions are valid upstream.
    import yaml
    data = yaml.safe_load(front)
    if not isinstance(data, dict) or not all(isinstance(data.get(k), str) for k in ('name', 'description')):
        raise ValueError(f'{path}: invalid name/description')
    return data, body.lstrip()

def generate(root=ROOT):
    out = root / '.codex/agents'
    out.mkdir(parents=True, exist_ok=True)
    for path in sorted((root / '.codex/roles').glob('*.md')):
        data, body = frontmatter(path)
        fields = {'name': data['name'], 'description': data['description'], 'developer_instructions': RUNTIME + body}
        text = '# Generated by python tools/studio.py generate; edit .codex/roles instead.\n'
        text += ''.join(f'{key} = {json.dumps(value, ensure_ascii=False)}\n' for key, value in fields.items())
        (out / (data['name'] + '.toml')).write_text(text, encoding='utf-8', newline='\n')

def check(root=ROOT):
    errors = []
    manifest = json.loads((root / '.codex/port-manifest.json').read_text(encoding='utf-8'))
    for folder, names, suffix in [('.agents/skills', manifest['skills'], '/SKILL.md'), ('.codex/roles', manifest['roles'], '.md')]:
        for name in names:
            p = root / folder / (name + suffix)
            try:
                data, body = frontmatter(p)
                if data['name'] != name or not body.strip():
                    errors.append(f'{p}: name/body mismatch')
                if set(data) != {'name', 'description'}:
                    errors.append(f'{p}: unsupported frontmatter fields')
                if re.search(r'^!`|^@\S|CLAUDE_SKILL_DIR|AskUserQuestion|\$ARGUMENTS', body, re.M):
                    errors.append(f'{p}: unported runtime syntax')
            except (ValueError, OSError) as exc:
                errors.append(str(exc))
    for name in manifest['roles']:
        try:
            p = root / '.codex/agents' / (name + '.toml')
            data = tomllib.loads(p.read_text(encoding='utf-8'))
            source, body = frontmatter(root / '.codex/roles' / (name + '.md'))
            if data != {'name': name, 'description': source['description'], 'developer_instructions': RUNTIME + body}:
                errors.append(f'{p}: stale generated agent; run generate')
        except (ValueError, OSError) as exc:
            errors.append(str(exc))
    for p in (root / '.codex').glob('*.toml'):
        try:
            tomllib.loads(p.read_text(encoding='utf-8'))
        except ValueError as exc:
            errors.append(f'{p}: {exc}')
    hooks = json.loads((root / '.codex/hooks.json').read_text(encoding='utf-8'))
    for event, groups in hooks['hooks'].items():
        for group in groups:
            for hook in group['hooks']:
                if f'codex_adapter.py {event}' not in hook['command']:
                    errors.append(f'{event}: adapter not configured')
    license_text = (root / 'LICENSE').read_text(encoding='utf-8')
    if 'Copyright (c) 2026 Donchitos' not in license_text:
        errors.append('Original copyright missing')
    print(json.dumps({'roles': len(manifest['roles']), 'skills': len(manifest['skills']), 'errors': errors}, indent=2))
    return 1 if errors else 0

def doctor(root=ROOT):
    report = {'python': sys.version.split()[0], 'root': str(root), 'tools': {}, 'warnings': []}
    for command in ('git', 'bash', 'codex'):
        found = shutil.which(command)
        report['tools'][command] = found
        if not found:
            report['warnings'].append(f'{command} unavailable on PATH')
    try:
        import yaml
        report['yaml'] = yaml.__version__
        config = yaml.safe_load((root / 'project.yaml').read_text(encoding='utf-8'))
        report['engine_configured'] = bool((config or {}).get('engine'))
    except (ImportError, ValueError, OSError) as exc:
        report['warnings'].append(str(exc))
    report['hook_trust'] = 'Not probed: review .codex/hooks.json with /hooks in the host'
    report['runtime_validation'] = 'Not performed: doctor does not invoke a model or game engine'
    print(json.dumps(report, indent=2))
    return int(bool(report['warnings']))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['generate', 'check', 'doctor'])
    args = parser.parse_args()
    if args.command == 'generate':
        generate()
        sys.exit(check())
    sys.exit(check() if args.command == 'check' else doctor())
